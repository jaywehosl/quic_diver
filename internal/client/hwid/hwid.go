// Package hwid — отпечаток машины клиента.
//
// Нужен для учёта устройств: сколько машин ходит под одним токеном и какую из
// них администратор отзывает поимённо (см. учёт на узле).
//
// Границы честно: отпечаток считает сам клиент, поэтому пропатченный клиент
// подделает его без труда — закрытый исходник это лишь удорожает. Значит hwid —
// заслон от бытовой раздачи токена знакомым, а не средство защиты. Настоящий
// предел ставит узел лимитом одновременных сессий: живое соединение подделать
// нельзя.
//
// Требования к значению: пережить переустановку клиента (иначе учёт слетал бы
// после каждого обновления) и отличаться на разных машинах, включая второго
// пользователя той же ОС и виртуалку. Поэтому берём идентификатор, который
// выдаёт система, а не то, что мы сами куда-то записали.
package hwid

import (
	"crypto/sha256"
	"encoding/hex"
	"strings"
	"sync"
)

// cached — отпечаток считается один раз за запуск: он не меняется, а лезть в
// реестр или /etc на каждое подключение незачем.
var (
	once   sync.Once
	cached string
)

// Get возвращает отпечаток машины (hex, 32 символа).
//
// Не смог определить — вернёт пустую строку: узел в этом случае просто не ведёт
// учёт устройств для клиента. Отказывать в связи из-за неопознанной машины
// нельзя, иначе экзотическая система осталась бы без интернета.
func Get() string {
	once.Do(func() {
		raw := machineID()
		if raw == "" {
			return
		}
		// Хешируем, а не шлём как есть: сырой machine-id — идентификатор ОС, и
		// светить им в чужой базе незачем. Соль привязывает отпечаток к нашему
		// приложению, чтобы он не совпадал с чужими сервисами.
		sum := sha256.Sum256([]byte("quicdiver-hwid\x00" + raw))
		cached = hex.EncodeToString(sum[:16])
	})
	return cached
}

// normalize приводит сырой идентификатор к сравнимому виду.
func normalize(s string) string {
	return strings.ToLower(strings.TrimSpace(strings.Trim(s, "\x00\r\n{}")))
}
